// Перша згадка кожного терміна в шматку тексту стає посиланням; шматок — це
// цілий розділ Довідки, тож посилання одне на розділ, а не в кожному абзаці (у
// «Мапі сайту» «скрапер» стоїть майже в кожному пункті, і текст рябів би). Лише
// в тексті: усередині тегів, посилань, <code> і заголовків термінів нічого не чіпаємо. self — термін, який цей
// текст саме тлумачить: на себе він не посилається. Збіги шукаються в
// оригінальному тексті й вставляються разом, щоб одна вставка (з її data-tip)
// не стала полем пошуку для наступного терміна.
function linkTerms(html, self) {
  const used = new Set();
  let skip = 0, label = false;
  return html.split(/(<[^>]+>)/).map(part => {
    if (part.startsWith('<')) {
      if (/^<(a|code)[\s>]/i.test(part)) skip++;
      else if (/^<\/(a|code)>/i.test(part)) skip = Math.max(0, skip - 1);
      else if (/class="help-term-label"/.test(part)) { skip++; label = true; }
      else if (label && /^<\/div>/i.test(part)) { skip = Math.max(0, skip - 1); label = false; }
      return part;
    }
    if (skip || !part.trim()) return part;
    const hits = [];
    for (const g of GLOSSARY) {
      if (!g.rx || g.id === self || used.has(g.id)) continue;
      const m = g.rx.exec(part);
      if (!m) continue;
      const [s, e] = [m.index, m.index + m[0].length];
      if (hits.some(h => s < h.e && e > h.s)) continue;
      hits.push({ s, e, g });
      used.add(g.id);
    }
    hits.sort((x, y) => x.s - y.s);
    let out = '', at = 0;
    for (const h of hits) {
      out += part.slice(at, h.s) + `<a class="gl" href="#terms/${h.g.id}" data-tip="${escapeHtmlOuter(h.g.short)}">${part.slice(h.s, h.e)}</a>`;
      at = h.e;
    }
    return out + part.slice(at);
  }).join('');
}


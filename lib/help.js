// Логотипи копіюються в output/site/logos/ один раз на збірку: вони однакові
// для всіх сторінок, тож лежать окремими файлами, а не вбудовані в HTML.
// Переважно SVG; nic.ua віддає свій знак лише растром (їхній SVG — широкий
// логотип-напис 98×27, у квадраті 30×30 він став би нечитним), тож там PNG
// 152×152 — його ж apple-touch-icon.
function writeLogos(outDir) {
  const dir = path.join(outDir, 'logos');
  fs.mkdirSync(dir, { recursive: true });
  for (const name of fs.readdirSync(LOGO_SRC)) {
    if (!/\.(svg|png)$/.test(name)) continue;
    fs.copyFileSync(path.join(LOGO_SRC, name), path.join(dir, name));
  }
}


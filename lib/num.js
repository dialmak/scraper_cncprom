// Числа зі знаком для людей: справжній мінус «−» (U+2212), а не дефіс «-»; він ширший
// і стоїть на рівні середини цифр (користувач 28.09.2026). Лише для тексту, який
// бачить людина: у JSON і логах числа лишаються числами.

// −1, 0, 3 (без плюса) — для колонок, де знак бачимо лише в мінуса.
const num = n => (n < 0 ? '−' + Math.abs(n) : String(n));

// −1, 0, +3 — для різниць, де плюс теж щось означає.
const signed = n => (n > 0 ? '+' + n : num(n));

module.exports = { num, signed };
